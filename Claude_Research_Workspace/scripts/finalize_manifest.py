#!/usr/bin/env python
"""finalize_manifest.py - adds media, figure and deliverable records to sources/manifest.json and prints an asset summary."""
import json, pathlib, time
ROOT = pathlib.Path(__file__).resolve().parent.parent
mf = json.loads((ROOT / "sources" / "manifest.json").read_text(encoding="utf-8"))
media = []
lic = {}
lp = ROOT / "sources" / "media" / "commons_media_licenses.txt"
if lp.exists():
    for line in lp.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) >= 4:
            lic[parts[0]] = {"license": parts[1], "author": parts[2], "url": parts[3]}
for f in sorted((ROOT / "sources" / "media").glob("*")):
    if f.suffix.lower() not in (".jpg", ".png", ".webm"):
        continue
    rec = {"local_path": str(f.relative_to(ROOT)), "title": f.name}
    if f.name.startswith("kth2022_fig"):
        rec.update({"url": "https://www.frontiersin.org/articles/10.3389/fmats.2022.978861/full", "doi": "10.3389/fmats.2022.978861",
                    "license": "CC BY 4.0", "authors": ["Chunxin Liu", "Taras Oriekhov", "Michael Fokine"], "year": 2022,
                    "relevance_summary": "Figure from the KTH filament-based glass 3D printing study (setup, bonding widths, multilayer walls)"})
    elif "Caustic" in f.name:
        rec.update({"url": "https://commons.wikimedia.org/wiki/File:Caustic_patterns_of_a_3D_printed_glass_structure.jpg",
                    "license": "CC BY-SA 4.0", "authors": ["Neri Oxman"], "year": 2015,
                    "relevance_summary": "Photograph of MIT G3DP printed glass lamps showing caustic projection from layer seams"})
    media.append(rec)
figures = []
for f in sorted((ROOT / "latex" / "figures").glob("*")):
    figures.append({"local_path": str(f.relative_to(ROOT)), "title": f.name,
                    "relevance_summary": "Generated by scripts/make_figures.py from cited fixed points and textbook relations" if f.suffix == ".pdf"
                    else "Copied licensed image used in the monograph"})
mf["media"] = media
mf["figures"] = figures
mf["deliverables"] = [
    {"local_path": "latex/build/main.pdf", "title": "Compiled monograph (Tectonic output)"},
    {"local_path": "glass_3d_printing_sota_monograph.pdf", "title": "Compiled monograph (copy at workspace root)"},
    {"local_path": "latex/references.bib", "title": "Validated BibTeX bibliography"},
    {"local_path": "sources/data/link_check.csv", "title": "Hyperlink validation results"},
    {"local_path": "sources/data/abstracts_dump.md", "title": "Reconstructed abstracts of all resolved works"},
]
mf["finalized"] = time.strftime("%Y-%m-%d %H:%M:%S")
(ROOT / "sources" / "manifest.json").write_text(json.dumps(mf, indent=1, ensure_ascii=False), encoding="utf-8")
papers = mf["papers"]
print("papers in manifest:", len(papers), "| resolved:", sum(1 for p in papers if p.get("resolved")),
      "| with local PDF:", sum(1 for p in papers if p.get("local_path")), "| with BibTeX:", sum(1 for p in papers if p.get("bibtex_path")))
print("patents:", len(mf["patents"]), "| media:", len(media), "| figures:", len(figures))
print("PDF files in sources/papers:", len(list((ROOT / "sources" / "papers").glob("*.pdf"))))
